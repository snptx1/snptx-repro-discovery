def fig_attention_probe() -> None:
    """Diagnose the constant incoming-attention sum; retain predictive AUROC separately."""
    _require(ART / "attention_attribution.json")
    _require(ART / "attention_nodes.npz")
    res = json.loads((ART / "attention_attribution.json").read_text())["results"]
    nodes = np.load(ART / "attention_nodes.npz")
    keys = list(res.keys())
    y = np.arange(len(keys))

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11.5, 4.8))
    bins = np.linspace(-16, 16, 49)
    for k, color in zip(keys, (NEON_YELLOW, NEON_BLUE)):
        scores = nodes[f"{k}__scores"]
        label = f"{_PRETTY[k].split(' (')[0]}: s.d. {scores.std():.2e} (n = {len(scores):,})"
        ax1.hist((scores - 1.0) * 1e8, bins=bins, density=True, histtype="step",
                 color=color, linewidth=1.3, label=label)
    ax1.axvline(0.0, color=TEXT_SECONDARY, ls="--", lw=1)
    ax1.set_xlabel(r"stored incoming sum $-\,1$ ($\times 10^{-8}$)")
    ax1.set_ylabel("density")
    ax1.set_title("Normalized incoming sum = 1", fontsize=10.5)
    ax1.legend(loc="upper left", fontsize=7.5)
    predaucs = [res[k]["test_auroc"] for k in keys]
    ax2.hlines(y, 0, predaucs, color=NEON_BLUE, linewidth=1.5)
    ax2.scatter(predaucs, y, color=NEON_BLUE, s=50, zorder=3)
    for yi, value in zip(y, predaucs):
        ax2.text(value + 0.025, yi, f"{value:.3f}", color=NEON_BLUE,
                 fontsize=9, va="center")
    ax2.axvline(0.5, color=TEXT_SECONDARY, ls="--", lw=1)
    ax2.set_xlim(0, 1)
    ax2.set_ylim(len(keys) - 0.4, -0.4)
    ax2.set_yticks(y)
    ax2.set_yticklabels([_PRETTY[k].split(" (")[0] for k in keys])
    ax2.set_xlabel("test AUROC (dashed = chance)")
