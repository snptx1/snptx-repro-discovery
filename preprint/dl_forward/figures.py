def _clf_endpoints(res: dict) -> list[str]:
    return [e.key for e in ENDPOINTS if e.task == "clf" and e.key in res]


def fig_ensemble_calibration() -> None:
    _require(ART / "ensemble_uncertainty.json")
    meta = json.loads((ART / "ensemble_uncertainty.json").read_text())
    res = meta["results"]
    keys = _clf_endpoints(res)
    methods = (("rf", C_RF, "RF"), ("gnn_single", C_SINGLE, "single"),
               ("mc_dropout", C_MC, "MC-drop"), ("ensemble", C_ENS, "ensemble"))
    panels = (("ece", "ECE (lower better)"), ("nll", "NLL (lower better)"),
              ("brier", "Brier (lower better)"))

    fig, axes = plt.subplots(1, 3, figsize=(13, 4))
    x = np.arange(len(keys))
    w = 0.2
    for ax, (metric, title) in zip(axes, panels):
        for j, (m, color, label) in enumerate(methods):
            vals = [res[k][m][metric] for k in keys]
            _neon_bar(ax, x + (j - 1.5) * w, vals, w, color, label=label)
        ax.set_xticks(x)
        ax.set_xticklabels([_PRETTY[k].split(" (")[0] for k in keys], rotation=20, fontsize=8.5)
        ax.set_title(title, fontsize=10.5)
    axes[0].legend(loc="best", fontsize=8.5)
    fig.suptitle("Deep-ensemble calibration vs baselines",
                 fontsize=13, fontweight="bold", color=TEXT_PRIMARY)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(FIGDIR / "fig_ensemble_calibration.png")
    plt.close(fig)
    print("wrote fig_ensemble_calibration.png")


def fig_conformal_efficiency() -> None:
    _require(ART / "ensemble_uncertainty.json")
    meta = json.loads((ART / "ensemble_uncertainty.json").read_text())
    res = meta["results"]
    keys = _clf_endpoints(res)
    methods = (("rf", C_RF, "RF"), ("gnn_single", C_SINGLE, "single"),
               ("mc_dropout", C_MC, "MC-drop"), ("ensemble", C_ENS, "ensemble"))

