def fig_transfer_curves() -> None:
    _require(ART / "multitask_metrics.json")
    _require(ART / "learning_curves.npz")
    meta = json.loads((ART / "multitask_metrics.json").read_text())
    z = np.load(ART / "learning_curves.npz")
    fracs = z["_fractions"]
    keys = [e.key for e in ENDPOINTS]

    n = len(keys)
    ncol = 3
    nrow = int(np.ceil(n / ncol))
    fig, axes = plt.subplots(nrow, ncol, figsize=(4.2 * ncol, 3.4 * nrow))
    axes = np.atleast_1d(axes).ravel()

    for ax, k in zip(axes, keys):
        task = meta["summary"][k]["task"]
        metric = "auroc" if task == "clf" else "mae"
        higher_better = task == "clf"
        for method, color, label in ((("rf", C_RF, "RF"),
                                      ("gnn_single", C_SINGLE, "GNN-single"),
                                      ("gnn_multi", C_MULTI, "GNN-multi"))):
            arr = z[f"{k}__{method}__{metric}"]  # (n_frac, n_seed)
            mean = np.nanmean(arr, axis=1)
            sd = np.nanstd(arr, axis=1)
            ax.plot(fracs, mean, "-o", color=color, label=label, lw=LW, ms=4)
            ax.fill_between(fracs, mean - sd, mean + sd, color=color, alpha=0.12)
        ax.set_title(f"{_PRETTY[k]}", fontsize=10.5)
        ax.set_xlabel("training fraction")
        ax.set_ylabel(metric.upper() + (" (lower better)" if not higher_better else ""))
        ax.set_xticks(fracs)
    for ax in axes[n:]:
        ax.axis("off")
    axes[0].legend(loc="best", fontsize=8.5)
    fig.suptitle("Multi-task representation transfer: data-efficiency curves",
                 fontsize=13, fontweight="bold", color=TEXT_PRIMARY)
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    fig.savefig(FIGDIR / "fig_transfer_curves.png")
    plt.close(fig)
    print("wrote fig_transfer_curves.png")


