def fig_pretrain_ablation() -> None:
    """Pretraining ablation: does self-supervised attribute-mask pretraining help?

    Bars show the beneficial-direction delta (pretrained - scratch) in each endpoint's
    primary metric at the lowest training fraction, for single- and multi-task trunks.
    For MAE endpoints the sign is flipped so that up = improvement for every endpoint.
    """
    _require(ART / "pretrain_ablation.json")
    d = json.loads((ART / "pretrain_ablation.json").read_text())
    summ = d["summary"]
    keys = [e.key for e in ENDPOINTS]
    frac = min(d["config"]["train_fractions"])

    # Per-seed paired deltas from the raw records, so the error bar is the sample s.d.
    per_seed: dict[tuple[str, str], np.ndarray] = {}
    for k in keys:
        metric = summ[k]["metric"]
        for arm in ("single", "multi"):
            runs = {(r["method"], r["seed"]): r[metric] for r in d["records"]
                    if r["endpoint"] == k and abs(r["fraction"] - frac) < 1e-9}
            seeds = sorted(s for (m, s) in runs if m == f"{arm}_scratch")
            per_seed[(k, arm)] = np.array(
                [runs[(f"{arm}_pretrained", s)] - runs[(f"{arm}_scratch", s)] for s in seeds])

    def _delta(k, arm):
        sign = -1.0 if summ[k]["metric"] == "mae" else 1.0  # up = improvement
        deltas = per_seed[(k, arm)]
        return sign * float(deltas.mean()), float(deltas.std(ddof=1))

    w = 0.38
    fig, axes = plt.subplots(1, 3, figsize=(13, 4.8), gridspec_kw={"width_ratios": [2, 1, 1]})
    panels = [([k for k in keys if summ[k]["metric"] == "auroc"], "Classification", "ΔAUROC"),
              (["solubility"], "Solubility", "−ΔMAE (logS)"),
              (["caco2"], "Caco2", "−ΔMAE (TDC target scale)")]
    for ax, (panel_keys, title, ylabel) in zip(axes, panels):
        x = np.arange(len(panel_keys))
        for off, arm, col, lab in ((-w / 2, "single", C_SINGLE, "single-task"),
                                   (w / 2, "multi", C_MULTI, "multi-task")):
            vals = [_delta(k, arm)[0] for k in panel_keys]
            errs = [_delta(k, arm)[1] for k in panel_keys]
            ax.bar(x + off, vals, w, yerr=errs, capsize=3,
                   color=to_rgba(col, BAR_FILL_ALPHA), edgecolor=col, linewidth=BAR_EDGE_LW,
                   ecolor=col, error_kw={"elinewidth": 1.0}, label=lab)
        ax.axhline(0.0, color=TEXT_SECONDARY, ls="--", lw=1)
        ax.set_xticks(x)
        ax.set_xticklabels([_PRETTY[k].split(" (")[0] for k in panel_keys])
        ax.set_ylabel(ylabel, fontsize=10)
        ax.set_title(title, fontsize=10.5)
        ax.set_xlim(-0.6, len(panel_keys) - 0.4)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=2, fontsize=9)
    fig.suptitle(f"Attribute-mask pretraining at retained scaffold fraction {frac:.2f}\n"
                 "Paired beneficial-direction changes; mean ± sample s.d. over five seeds",
                 fontsize=13, fontweight="bold", color=TEXT_PRIMARY)
    fig.tight_layout(rect=(0, 0.08, 1, 0.98))
    fig.savefig(FIGDIR / "fig_pretrain_ablation.png")
    plt.close(fig)
    print("wrote fig_pretrain_ablation.png")


def fig_campaign_efficiency() -> None:
    """Retrospective stopping counts beside analytical requirements and subgroup caps."""
    from scipy.stats import norm

    _require(ART / "campaign_learned.json")
    d = json.loads((ART / "campaign_learned.json").read_text())
    per = d["per_endpoint"]
    keys = list(per.keys())
    y = np.arange(len(keys))
    used = [per[k]["sprt"]["n_measurements"] for k in keys]
    fixed = [per[k]["sprt"]["fixed_sample_n"] for k in keys]
    cfg = d["sprt"]
    n_analytic = ((norm.ppf(1 - cfg["alpha"]) + norm.ppf(1 - cfg["beta"]))
                  / cfg["meaningful_effect_sigma"]) ** 2
    feasible = np.array(fixed) >= n_analytic - 0.05
    used_feasible = sum(u for u, ok in zip(used, feasible) if ok)
    analytic_feasible = n_analytic * int(feasible.sum())
    pct = 100 * (1 - used_feasible / analytic_feasible)

    fig, ax = plt.subplots(figsize=(11, 4.8))
    for yi, u, f, ok in zip(y, used, fixed, feasible):
        ax.plot([f, u], [yi, yi], color=BORDER, lw=2)
        if u == f:
            ax.text(u + 2, yi, f"{u} used / capped", color=TEXT_PRIMARY,
                    va="center", fontsize=8.5)
        else:
            ax.text(f + 1, yi - 0.14, f"{f:.1f}" + (" cap" if not ok else ""),
                    color=NEON_GREY, va="bottom", fontsize=8.5)
            ax.text(u + 1, yi + 0.14, str(u), color=NEON_BLUE, va="top", fontsize=8.5)
        if ok:
            difference = f - u
            note = (f"{difference:.1f} fewer" if difference >= 0
                    else f"{-difference:.1f} more")
        else:
            note = "cap; lower nominal power" if u != f else "subgroup exhausted; undecided"
        ax.text(96, yi, note, color=TEXT_SECONDARY, va="center", fontsize=8.5)
    ax.scatter(np.array(fixed)[feasible], y[feasible], color=NEON_GREY, marker="s",
               s=65, zorder=3, label="analytical fixed-sample requirement")
    ax.scatter(np.array(fixed)[~feasible], y[~feasible], facecolors="none", edgecolors=NEON_GREY,
               marker="s", s=75, linewidths=1.5, zorder=3, label="available subgroup cap")
    ax.scatter(used, y, color=NEON_BLUE, s=65, zorder=4, label="SPRT measurements used")
    ax.set_xlim(0, 142)
    ax.set_ylim(len(keys) - 0.4, -0.4)
    ax.set_yticks(y)
    verdicts = {"reject_h0": "GO", "accept_h0": "NO-GO", "continue": "EXHAUSTED"}
    ax.set_yticklabels([
        f"{_PRETTY[k].split(' (')[0]} · {verdicts[per[k]['sprt']['decision']]}"
        for k in keys])
    for tick, k in zip(ax.get_yticklabels(), keys):
        tick.set_color(NEON_YELLOW if per[k]["sprt"]["decision"] == "continue" else NEON_GREEN)
    ax.set_xlabel("measurements used / analytical benchmark")
    ax.set_title(f"BBB + AMES: {used_feasible} used vs {analytic_feasible:.1f} analytical requirement "
                 f"({pct:.1f}% fewer)\nhERG and HIA comparators are capped below nominal power",
                 fontsize=10.5)
    handles, labels = ax.get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=3, fontsize=8)
    fig.suptitle("Retrospective stopping on the ensemble-ranked subgroups",
                 fontsize=13, fontweight="bold", color=TEXT_PRIMARY)
    fig.tight_layout(rect=(0, 0.09, 1, 0.92))
    fig.savefig(FIGDIR / "fig_campaign_efficiency.png")
    plt.close(fig)
    print("wrote fig_campaign_efficiency.png")


def main() -> None:
    made = []
    if (ART / "multitask_metrics.json").exists():
        fig_transfer_curves()
        made.append("transfer")
    if (ART / "ensemble_uncertainty.json").exists():
        fig_ensemble_calibration()
        fig_conformal_efficiency()
        made.append("ensemble")
    if (ART / "attention_attribution.json").exists():
        fig_attention_probe()
        made.append("attention")
    if (ART / "pretrain_ablation.json").exists():
        fig_pretrain_ablation()
        made.append("pretrain")
    if (ART / "campaign_learned.json").exists():
        fig_campaign_efficiency()
        made.append("campaign")
    if not made:
        raise SystemExit("no artifacts yet; run the GPU stage first")
    print("done:", made)


if __name__ == "__main__":
    main()
