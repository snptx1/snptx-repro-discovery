# Method colors, consistent across figures. House style: neon blue / yellow / pink,
# with a bright grey reserved for the reference/baseline series (no orange).
#   RF descriptor baseline -> grey     single-task GNN -> yellow
#   multi-task GNN         -> blue     MC-dropout      -> pink
#   deep ensemble          -> blue (bold; only co-occurs with rf/single/mc, not multi)
C_RF, C_SINGLE, C_MULTI = NEON_GREY, NEON_YELLOW, NEON_BLUE
C_ENS, C_MC = NEON_BLUE, NEON_PINK

# Thin, bright line/bar defaults so series stay legible on the dark canvas.
LW = 1.1
BAR_FILL_ALPHA = 0.22
BAR_EDGE_LW = 1.2


def _neon_bar(ax, x, height, w, color, label=None):
    """Thin neon bar: translucent fill under a bright, crisp edge of the same hue."""
    return ax.bar(x, height, w, color=to_rgba(color, BAR_FILL_ALPHA),
                  edgecolor=color, linewidth=BAR_EDGE_LW, label=label)

_PRETTY = {e.key: e.pretty for e in ENDPOINTS}


def _require(path: Path) -> None:
    if not path.exists():
        raise SystemExit(f"missing artifact {path}; run the GPU stage first "
                         f"(make train-gnn / make_ensemble_uncertainty.py)")


