def fig_attention_probe() -> None:
    """Interpretability probe: does attention recover the descriptor rule?"""
    _require(ART / "attention_attribution.json")
    res = json.loads((ART / "attention_attribution.json").read_text())["results"]
    keys = list(res.keys())
    x = np.arange(len(keys))
    w = 0.38

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10.5, 4.2))
    aucs = [res[k]["node_attention_auroc"] for k in keys]
    predaucs = [res[k]["test_auroc"] for k in keys]
    ax1.bar(x - w / 2, aucs, w, color=to_rgba(NEON_YELLOW, BAR_FILL_ALPHA),
            edgecolor=NEON_YELLOW, linewidth=BAR_EDGE_LW, label="attention → salience AUROC")
    ax1.bar(x + w / 2, predaucs, w, color=to_rgba(NEON_BLUE, BAR_FILL_ALPHA),
            edgecolor=NEON_BLUE, linewidth=BAR_EDGE_LW, label="GAT predictive AUROC")
    ax1.axhline(0.5, color=BORDER, ls="--", lw=1.2)
    ax1.text(len(keys) - 0.5, 0.52, "chance", color=TEXT_SECONDARY, fontsize=8.5, ha="right")
    ax1.set_xticks(x)
    ax1.set_xticklabels([_PRETTY[k].split(" (")[0] for k in keys])
    ax1.set_ylim(0, 1.0)
    ax1.set_title("Attention does not recover the descriptor rule", fontsize=10.5)
    ax1.legend(loc="lower right", fontsize=8.5)
    enr = [res[k]["topk_enrichment"] for k in keys]
    # pink = positive enrichment, grey = non-positive (near-zero / negative).
    colors = [NEON_PINK if v > 0 else NEON_GREY for v in enr]
    ax2.bar(x, enr, 0.5, color=[to_rgba(c, BAR_FILL_ALPHA) for c in colors],
            edgecolor=colors, linewidth=BAR_EDGE_LW)
    ax2.axhline(0.0, color=BORDER, ls="--", lw=1.2)
    ax2.set_xticks(x)
    ax2.set_xticklabels([_PRETTY[k].split(" (")[0] for k in keys])
    ax2.set_title("Top-3 attended-atom salient enrichment (near 0)", fontsize=10.5)
    fig.suptitle("Interpretability probe: attention vs descriptor atom salience",
                 fontsize=13, fontweight="bold", color=TEXT_PRIMARY)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(FIGDIR / "fig_attention_probe.png")
    plt.close(fig)
    print("wrote fig_attention_probe.png")


def fig_pretrain_ablation() -> None:
    """Pillar-1 ablation: does self-supervised node-mask pretraining help?

    Bars show the beneficial-direction delta (pretrained - scratch) in each endpoint's
    primary metric at the lowest training fraction, for single- and multi-task trunks.
    For MAE endpoints the sign is flipped so that up = improvement for every endpoint.
    """
    _require(ART / "pretrain_ablation.json")
    d = json.loads((ART / "pretrain_ablation.json").read_text())
    summ = d["summary"]
    keys = [e.key for e in ENDPOINTS]
    frac = min(d["config"]["train_fractions"])

    def _delta(k, arm):
        row = next(r for r in summ[k][arm] if abs(r["fraction"] - frac) < 1e-9)
        sign = -1.0 if summ[k]["metric"] == "mae" else 1.0  # up = improvement
        return sign * row["delta_mean"], row["delta_std"]

    x = np.arange(len(keys))
    w = 0.38
    fig, ax = plt.subplots(figsize=(10.5, 4.6))
    for off, arm, col, lab in ((-w / 2, "single", C_SINGLE, "single-task"),
                               (w / 2, "multi", C_MULTI, "multi-task")):
        vals = [_delta(k, arm)[0] for k in keys]
        errs = [_delta(k, arm)[1] for k in keys]
        ax.bar(x + off, vals, w, yerr=errs, capsize=3,
               color=to_rgba(col, BAR_FILL_ALPHA), edgecolor=col, linewidth=BAR_EDGE_LW,
               ecolor=col, error_kw={"elinewidth": 1.0}, label=f"{lab} + pretrain")
    ax.axhline(0.0, color=BORDER, ls="--", lw=1.2)
    ax.set_xticks(x)
    ax.set_xticklabels([_PRETTY[k].split(" (")[0] for k in keys])
    ax.set_ylabel(f"improvement from pretraining\n(beneficial direction, fraction {frac})")
    ax.set_title("Self-supervised node-mask pretraining (Hu et al. 2020): "
                 "delta over from-scratch", fontsize=11)
    ax.text(-0.45, 0.006, "no effect", color=TEXT_SECONDARY,
            fontsize=8.5, ha="left", va="bottom")
    ax.legend(loc="upper right", fontsize=9)
    fig.suptitle("Pillar-1 ablation: pretraining vs scratch at low data",
                 fontsize=13, fontweight="bold", color=TEXT_PRIMARY)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(FIGDIR / "fig_pretrain_ablation.png")
    plt.close(fig)
    print("wrote fig_pretrain_ablation.png")


def fig_campaign_efficiency() -> None:
    """Learned-oracle campaign: measurements used vs the fixed-sample budget, per endpoint.

    Sequential SPRT with the deep-ensemble oracle should reach a decision in fewer
    measurements than a fixed-sample design where the oracle's top-ranked subgroup is
    enriched. We plot both bars per endpoint and annotate the aggregate saving; the harder
    cases (BBB spends more, HIA undecided) are shown, not hidden.
    """
    _require(ART / "campaign_learned.json")
    d = json.loads((ART / "campaign_learned.json").read_text())
    per = d["per_endpoint"]
    s = d["summary"]
    keys = list(per.keys())
    x = np.arange(len(keys))
    w = 0.36
    used = [per[k]["sprt"]["n_measurements"] for k in keys]
    fixed = [per[k]["sprt"]["fixed_sample_n"] for k in keys]

    fig, ax = plt.subplots(figsize=(9.5, 4.6))
    # fixed-sample budget = grey reference; sequential (used) = bright blue.
    _neon_bar(ax, x - w / 2, fixed, w, NEON_GREY, label="fixed-sample budget")
    _neon_bar(ax, x + w / 2, used, w, NEON_BLUE, label="SPRT (sequential) used")
    for xi, (u, f) in enumerate(zip(used, fixed)):
        verdict = per[keys[xi]]["sprt"]["verdict"].split(" (")[0]
        ax.text(xi, max(u, f) + 2, verdict, ha="center", va="bottom",
                fontsize=8.0, color=TEXT_SECONDARY)
    ax.set_xticks(x)
    ax.set_xticklabels([_PRETTY[k].split(" (")[0] for k in keys])
    ax.set_ylabel("measurements to a decision")
    ax.set_title(f"Learned-oracle campaign: {s['total_measurements_used']} vs "
                 f"{s['total_fixed_sample']:.0f} measurements "
                 f"({s['pct_saved']}% saved, {s['n_go_decisions']}/{s['n_endpoints']} GO)",
                 fontsize=11)
    ax.legend(loc="upper right", fontsize=9)
    fig.suptitle("Sequential decision efficiency with the deep-ensemble oracle",
                 fontsize=13, fontweight="bold", color=TEXT_PRIMARY)
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(FIGDIR / "fig_campaign_efficiency.png")
    plt.close(fig)
    print("wrote fig_campaign_efficiency.png")


