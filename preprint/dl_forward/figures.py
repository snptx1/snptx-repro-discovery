# Method colors, consistent across figures. House style: neon blue / yellow / green,
# with a bright grey reserved for the reference/baseline series (no orange).
#   RF descriptor baseline -> grey     single-task GNN -> yellow
#   multi-task GNN         -> blue     MC-dropout      -> green
#   deep ensemble          -> blue (bold; only co-occurs with rf/single/mc, not multi)
C_RF, C_SINGLE, C_MULTI = NEON_GREY, NEON_YELLOW, NEON_BLUE
C_ENS, C_MC = NEON_BLUE, NEON_GREEN

# Thin, bright line/bar defaults so series stay legible on the dark canvas.
LW = 1.1
BAR_FILL_ALPHA = 0.22
BAR_EDGE_LW = 1.2


def _horizontal_comparison(ax, keys, res, metric, methods, baseline=0.0):
    """Show endpoint values with offset horizontal lines and distinct method markers."""
    y = np.arange(len(keys))
    for j, (method, color, label, marker) in enumerate(methods):
        values = [res[k][method][metric] for k in keys]
        positions = y + (j - (len(methods) - 1) / 2) * 0.18
        ax.hlines(positions, baseline, values, colors=color, linewidth=1.5)
        ax.plot(values, positions, marker, color=color, markersize=4, label=label)
    ax.set_yticks(y)
    ax.set_yticklabels([_PRETTY[k].split(" (")[0] for k in keys], fontsize=8.5)
    ax.invert_yaxis()
    ax.set_xlim(left=baseline)


def _uncertainty_methods():
    return (("rf", C_RF, "RF", "s"), ("gnn_single", C_SINGLE, "single GIN", "o"),
            ("mc_dropout", C_MC, "MC dropout", "^"),
            ("ensemble", C_ENS, "ensemble", "D"))

_PRETTY = {e.key: e.pretty for e in ENDPOINTS}


def _require(path: Path) -> None:
    if not path.exists():
        raise SystemExit(f"missing artifact {path}; regenerate its source results first")


